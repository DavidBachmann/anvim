---@module "luassert"

local compose = require("anvim.compose")
local follow = require("anvim.follow")
local helpers = require("helpers")
local input = require("anvim.input")
local layout = require("anvim.layout")

local api = vim.api

local function feed(keys)
  api.nvim_feedkeys(vim.keycode(keys), "mxt", false)
  vim.wait(20)
end

local function prompt(lines)
  if lines then
    api.nvim_buf_set_lines(input.buf(), 0, -1, false, lines)
  end
  return helpers.buf_lines(input.buf())
end

-- The prompt has focus in normal mode, with lines and the cursor at pos.
local function in_prompt(lines, pos)
  helpers.start()
  vim.cmd.stopinsert()
  if compose.win() then
    api.nvim_win_close(compose.win(), true)
  end
  api.nvim_set_current_win(layout.wins.input)
  prompt(lines)
  api.nvim_win_set_cursor(0, pos)
  vim.wait(20)
end

local function compose_buf()
  return api.nvim_win_get_buf((assert(compose.win(), "no compose window")))
end

local function closed()
  return vim.wait(500, function()
    return compose.win() == nil
  end)
end

describe("compose", function()
  it("opens the prompt's text in the middle of the screen, at the same place, and <C-g> goes back", function()
    in_prompt({ "fix the bug", "in @matchparen.lua" }, { 2, 4 })
    feed("<C-g>")
    local win = assert(compose.win(), "<C-g> opened no window")
    assert.are.same(win, api.nvim_get_current_win())
    local config = api.nvim_win_get_config(win)
    assert.are.same("editor", config.relative)
    assert.is_true(math.abs(config.col + config.width / 2 - vim.o.columns / 2) <= 2, "not in the middle")
    local buf = compose_buf()
    assert.are.same({ "fix the bug", "in @matchparen.lua" }, helpers.buf_lines(buf))
    assert.are.same({ 2, 4 }, api.nvim_win_get_cursor(win))
    assert.are.same("anvim_input", vim.bo[buf].filetype)
    assert.are.same("acwrite", vim.bo[buf].buftype)
    assert.is_true(vim.bo[buf].modifiable)
    assert.is_false(vim.bo[buf].modified)
    assert.are.same("", vim.wo[win].winbar)
    assert.is_true(follow.enabled(), "follow mode counts the compose window as the prompt")

    feed("A, now<C-g>")
    assert.is_true(closed(), "<C-g> did not close the window")
    assert.are.same(layout.wins.input, api.nvim_get_current_win())
    assert.are.same({ "fix the bug", "in @matchparen.lua, now" }, prompt())
    assert.is_false(api.nvim_buf_is_valid(buf), "the compose buffer was not wiped")
  end)

  it("adds lines with Enter, puts the text in the prompt with :w, and :wq goes back where typing stopped", function()
    in_prompt({ "hello world" }, { 1, 0 })
    helpers.capture_sends(function(sent)
      feed("<C-g>")
      feed("A<CR>second line<Esc>")
      assert.are.same({}, sent, "Enter sent the prompt")
    end)
    assert.are.same({ "hello world" }, prompt(), "the prompt changed before :w")
    feed(":w<CR>")
    assert.are.same({ "hello world", "second line" }, prompt())
    assert.is_false(vim.bo[compose_buf()].modified)
    feed("gg0wibig <Esc>")
    feed(":wq<CR>")
    assert.is_true(closed(), ":wq did not close the window")
    vim.wait(20)
    assert.are.same({ "hello big world", "second line" }, prompt())
    assert.are.same(layout.wins.input, api.nvim_get_current_win())
    assert.are.same({ 1, 10 }, api.nvim_win_get_cursor(0), "typing goes on after 'big '")
  end)

  it("keeps the prompt as it was after :q!, and :q does not drop changes", function()
    in_prompt({ "keep me" }, { 1, 0 })
    feed("<C-g>")
    feed("ccthrown away<Esc>")
    assert.is_false(pcall(vim.cmd.quit), ":q dropped the changes")
    assert.is_not_nil(compose.win())
    feed(":q!<CR>")
    assert.is_true(closed(), ":q! did not close the window")
    vim.wait(20)
    assert.are.same({ "keep me" }, prompt())
    assert.are.same(layout.wins.input, api.nvim_get_current_win())
  end)

  it("puts the text in the prompt and closes when the cursor leaves it", function()
    in_prompt({ "" }, { 1, 0 })
    feed("<C-g>")
    feed("ityped, then left<Esc>")
    api.nvim_set_current_win(layout.code_win())
    assert.is_true(closed(), "the window stayed open")
    assert.are.same({ "typed, then left" }, prompt())
    assert.are.same(layout.wins.code, api.nvim_get_current_win())
  end)

  it("leaves <C-w>p in the prompt going to the window before it", function()
    in_prompt({ "" }, { 1, 0 })
    api.nvim_set_current_win(layout.code_win())
    vim.cmd.wincmd("l")
    vim.cmd.stopinsert()
    assert.are.same(layout.wins.input, api.nvim_get_current_win())
    feed("<C-g>")
    feed(":q<CR>")
    assert.is_true(closed())
    vim.cmd.stopinsert()
    vim.cmd.wincmd("p")
    assert.are.same(layout.wins.code, api.nvim_get_current_win())
  end)

  it("keeps <C-w>p going to the window before the prompt after a window key leaves it", function()
    in_prompt({ "" }, { 1, 0 })
    api.nvim_set_current_win(layout.code_win())
    vim.cmd.wincmd("l")
    vim.cmd.stopinsert()
    feed("<C-g>")
    feed("Atwo<Esc>")
    vim.cmd.wincmd("h")
    assert.are.same(layout.wins.input, api.nvim_get_current_win(), "<C-w>h from a float goes to the prompt")
    assert.is_true(closed(), "leaving did not close the window")
    assert.are.same({ "two" }, prompt())
    vim.cmd.stopinsert()
    vim.cmd.wincmd("p")
    assert.are.same(layout.wins.code, api.nvim_get_current_win())
  end)

  it("shows no other buffer, and a split of it folds away with the text in the prompt", function()
    in_prompt({ "kept" }, { 1, 0 })
    feed("<C-g>")
    local buf = compose_buf()
    assert.is_false(pcall(vim.cmd.edit, helpers.tmp .. "/matchparen.lua"), ":edit showed another buffer")
    assert.are.same(buf, api.nvim_win_get_buf(compose.win()))
    feed("Ato the split<Esc>")
    vim.cmd.split()
    assert.is_true(closed(), "the split left the window open")
    for _, win in ipairs(api.nvim_tabpage_list_wins(0)) do
      assert.are_not.same("anvim_input", win ~= layout.wins.input and vim.bo[api.nvim_win_get_buf(win)].filetype)
    end
    assert.are.same({ "keptto the split" }, prompt())
    assert.are.same(layout.wins.input, api.nvim_get_current_win())
  end)
end)
