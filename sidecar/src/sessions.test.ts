import { describe, expect, test } from "bun:test";
import type { SessionMessage } from "@anthropic-ai/claude-agent-sdk";
import { historyEvents } from "./sessions";

// Messages in the shape getSessionMessages returns (SDK 0.3.304).
const base = { uuid: "u", session_id: "s", parent_tool_use_id: null, parent_agent_id: null };
const user = (content: unknown, extra: object = {}) =>
  ({ ...base, type: "user", message: { role: "user", content }, ...extra }) as unknown as SessionMessage;
const assistant = (content: unknown[], extra: object = {}) =>
  ({ ...base, type: "assistant", message: { role: "assistant", content }, ...extra }) as unknown as SessionMessage;

describe("historyEvents", () => {
  test("prompts, text and tool calls, with a Read's line count", () => {
    const events = historyEvents([
      user("<command-name>/clear</command-name>\n<command-message>clear</command-message>\n<command-args></command-args>", {
        isCompletedLocalCommand: true,
      }),
      { ...base, type: "system", message: undefined } as unknown as SessionMessage,
      user("Caveat: the messages below were generated by the user", { is_meta: true }),
      user("Count the lines"),
      assistant([{ type: "thinking", thinking: "" }]),
      assistant([{ type: "tool_use", id: "t1", name: "Read", input: { file_path: "/p/a.lua" } }]),
      user([{ type: "tool_result", tool_use_id: "t1", content: "1\tlocal M = {}\n2\t\n3\treturn M" }]),
      assistant([{ type: "tool_use", id: "t2", name: "Bash", input: { command: "false" } }]),
      user([{ type: "tool_result", tool_use_id: "t2", is_error: true, content: [{ type: "text", text: "Exit code 1" }] }]),
      assistant([{ type: "text", text: "It has 3 lines." }]),
      assistant([{ type: "tool_use", id: "c1", name: "Bash", input: { command: "ls" } }], { parent_tool_use_id: "t9" }),
      user([{ type: "text", text: "Look" }, { type: "image", source: {} }]),
    ]);
    expect(events).toEqual([
      { type: "user", text: "Count the lines" },
      { type: "tool_use", id: "t1", name: "Read", input: { file_path: "/p/a.lua" }, parent_id: null },
      {
        type: "tool_result",
        id: "t1",
        is_error: false,
        text: "1\tlocal M = {}\n2\t\n3\treturn M",
        result: { file: { numLines: 3 } },
        parent_id: null,
      },
      { type: "tool_use", id: "t2", name: "Bash", input: { command: "false" }, parent_id: null },
      { type: "tool_result", id: "t2", is_error: true, text: "Exit code 1", result: undefined, parent_id: null },
      { type: "text_start" },
      { type: "text_delta", text: "It has 3 lines." },
      { type: "text_stop" },
      { type: "user", text: "Look\n[Image]" },
    ]);
  });

  test("Claude Code's interrupt markers are notices, not prompts", () => {
    const events = historyEvents([
      user("Run the tests"),
      user([{ type: "text", text: "[Request interrupted by user for tool use]" }]),
      user("[Request interrupted by user]"),
    ]);
    expect(events).toEqual([
      { type: "user", text: "Run the tests" },
      { type: "notice", level: "warn", text: "Interrupted by user" },
      { type: "notice", level: "warn", text: "Interrupted by user" },
    ]);
  });

  // As Claude Code 2.1.304 saves a background agent's end, and a shell's.
  test("a background agent's notification is its end, not a prompt", () => {
    const origin = { origin: { kind: "task-notification", producer: "session-task", runId: "r1" } };
    const events = historyEvents([
      user(
        [
          "<task-notification>",
          "<task-id>aa666b4d4824e8e44</task-id>",
          "<tool-use-id>toolu_01NX</tool-use-id>",
          "<output-file>/tmp/tasks/aa666b4d4824e8e44.output</output-file>",
          "<status>completed</status>",
          '<summary>Agent "Add FAST line to alpha.js" finished</summary>',
          "<note>A task-notification fires each time this agent stops.</note>",
          "<result>Added `// edited by FAST` as the first line of alpha.js.</result>",
          "<usage><subagent_tokens>16061</subagent_tokens><tool_uses>2</tool_uses><duration_ms>7469</duration_ms></usage>",
          "</task-notification>",
        ].join("\n"),
        origin,
      ),
      user(
        "<task-notification>\n<task-id>b8u5jl1cw</task-id>\n<tool-use-id>toolu_B</tool-use-id>\n<status>completed</status>\n" +
          '<summary>Background command "Wait 10 seconds" completed (exit code 0)</summary>\n</task-notification>',
        origin,
      ),
    ]);
    expect(events).toEqual([
      {
        type: "agent_end",
        agent_id: "aa666b4d4824e8e44",
        tool_use_id: "toolu_01NX",
        status: "completed",
        description: "Add FAST line to alpha.js",
        summary: "Added `// edited by FAST` as the first line of alpha.js.",
        tool_uses: 2,
        tokens: 16061,
        duration_ms: 7469,
      },
    ]);
  });

  test("slash commands, their output and compaction", () => {
    const events = historyEvents([
      user("This session is being continued from a previous conversation", { is_meta: true, isCompactSummary: true }),
      user("<command-name>/compact</command-name>\n<command-message>compact</command-message>\n<command-args>keep the API notes</command-args>"),
      user("<local-command-stdout>Compacted </local-command-stdout>"),
      user("<local-command-stdout></local-command-stdout>"),
    ]);
    expect(events).toEqual([
      { type: "compact" },
      { type: "user", text: "/compact keep the API notes" },
      { type: "output", text: "Compacted" },
    ]);
  });
});
